import { useCallback, useState } from "react";
import { useAuth } from "../AuthContext";
import { apiFetch, apiCall } from "../api";
import { useApi } from "../lib/useApi";
import { useToast } from "../components/Toast";
import { fmtMoney } from "../lib/format";
import { hasRole } from "../lib/roles";
import SqlPanel from "../components/SqlPanel";
import DataTable from "../components/DataTable";
import PageHeader from "../components/PageHeader";
import Field from "../components/Field";
import LookupSelect from "../components/LookupSelect";
import StatusBadge from "../components/StatusBadge";
import { inputCls, panelCls, panelHeadCls, btnPrimary, btnGhost, btnSmallGhost } from "../components/ui";
import { Receipt, CreditCard, RefreshCw, FileText, AlertTriangle } from "lucide-react";

const MODES = ["CASH", "CARD", "UPI", "INSURANCE", "NET_BANKING"];

export default function BillingPage() {
  const { auth } = useAuth();
  const toast = useToast();
  const isBilling = hasRole(auth, "billingclerk");
  const [patientId, setPatientId] = useState("");
  const [summary, setSummary] = useState(null);
  const [items, setItems] = useState(null);
  const [payment, setPayment] = useState({ bill_id: "", amount_paid: "", payment_mode: "UPI" });
  const [gen, setGen] = useState({ appointment_id: "", patient_id: "" });
  const [lastAction, setLastAction] = useState(null);
  const [bucket, setBucket] = useState("");

  const fetchOutstanding = useCallback((token) => isBilling
    ? apiFetch("/billing/outstanding", { token, params: { bucket } }) : Promise.resolve(null), [bucket, isBilling]);
  const outstanding = useApi(fetchOutstanding);

  async function loadSummary(pid = patientId) {
    if (!pid) return;
    try { setSummary(await apiFetch(`/billing/summary/${pid}`, { token: auth.token })); setItems(null); }
    catch (err) { toast.error(err.message); }
  }

  async function showItems(billId) {
    try { setItems({ billId, ...(await apiFetch(`/billing/bills/${billId}/items`, { token: auth.token })) }); }
    catch (err) { toast.error(err.message); }
  }

  async function submitPayment(e) {
    e.preventDefault();
    try {
      const res = await apiCall("/billing/payments", { token: auth.token, params: payment });
      setLastAction({ label: `Payment ${res.payment_id} recorded via record_payment() — trigger set bill ${payment.bill_id} to ${res.bill_status_after_trigger}, balance ${fmtMoney(res.balance)}`, res });
      toast.success(`Payment recorded — bill now ${res.bill_status_after_trigger}`);
      setPayment({ ...payment, amount_paid: "" });
      if (patientId) loadSummary();
      outstanding.reload();
    } catch (err) { setLastAction({ label: "Payment refused", error: err.message }); toast.error(err.message); }
  }

  async function generate(e) {
    e.preventDefault();
    try {
      const res = await apiCall(`/billing/generate/${gen.appointment_id}`, { token: auth.token, params: { patient_id: gen.patient_id } });
      setLastAction({ label: `Bill ${res.bill_id} generated by generate_bill() (consultation + that visit's lab tests)`, res });
      toast.success(`Bill ${res.bill_id} generated`);
      setPatientId(gen.patient_id); loadSummary(gen.patient_id);
    } catch (err) { setLastAction({ label: "Bill generation refused", error: err.message }); toast.error(err.message); }
  }

  return (
    <div>
      <PageHeader title="Billing & payments" subtitle="Bills, ageing of outstanding amounts and concurrency-safe payments (SELECT … FOR UPDATE in record_payment, status flip by a compound trigger)." />

      {lastAction && (
        <div className={`${panelCls} border-l-4 ${lastAction.error ? "border-l-urgent" : "border-l-ok"}`}>
          <div className="text-sm font-medium">{lastAction.label}</div>
          {lastAction.error && <p className="text-urgent text-sm mt-1 mb-0">{lastAction.error}</p>}
          {lastAction.res && <SqlPanel sql={lastAction.res.sql_executed} meta={lastAction.res} defaultOpen />}
        </div>
      )}

      <div className="grid gap-5 lg:grid-cols-2">
        <div className={panelCls}>
          <div className={panelHeadCls}><h2 className="text-lg font-display m-0 flex items-center gap-2"><Receipt size={18} className="text-accent" /> Patient bills</h2></div>
          <form onSubmit={(e) => { e.preventDefault(); loadSummary(); }} className="flex items-end gap-3 flex-wrap">
            <div className="flex-1 min-w-[200px]">
              <LookupSelect label="Patient" value={patientId} onChange={setPatientId} lookupPath="/patients/search?last_name=" labelFn={(r) => `${r.patient_id} — ${r.first_name} ${r.last_name}`} />
            </div>
            <div className="mb-3.5"><button type="submit" className={btnPrimary}>Load</button></div>
          </form>
          {summary && (
            <>
              <div className="overflow-x-auto border border-border rounded-lg">
                <table className="w-full text-sm">
                  <thead><tr className="bg-surface-3/70 text-ink-muted text-[0.72rem] uppercase">
                    {["Bill", "Date", "Status", "Total", "Paid", "Balance", ""].map((h) => <th key={h} className="text-left px-3 py-2 border-b border-border-strong">{h}</th>)}
                  </tr></thead>
                  <tbody>
                    {summary.results.map((b) => (
                      <tr key={b.bill_id} className="even:bg-surface-2/50">
                        <td className="px-3 py-2 border-b border-border/70 font-mono text-xs">{b.bill_id}</td>
                        <td className="px-3 py-2 border-b border-border/70">{b.bill_date}</td>
                        <td className="px-3 py-2 border-b border-border/70"><StatusBadge status={b.status} /></td>
                        <td className="px-3 py-2 border-b border-border/70">{fmtMoney(b.total_amount)}</td>
                        <td className="px-3 py-2 border-b border-border/70">{fmtMoney(b.total_paid)}</td>
                        <td className="px-3 py-2 border-b border-border/70 font-medium">{fmtMoney(b.balance_due)}</td>
                        <td className="px-3 py-2 border-b border-border/70 space-x-1 whitespace-nowrap">
                          <button className={btnSmallGhost} onClick={() => showItems(b.bill_id)}><FileText size={12} /> Items</button>
                          {b.balance_due > 0 && isBilling && <button className={btnSmallGhost} onClick={() => setPayment({ ...payment, bill_id: String(b.bill_id), amount_paid: String(b.balance_due) })}>Pay</button>}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
              <SqlPanel sql={summary.sql_executed} meta={summary} />
            </>
          )}
          {items && (
            <div className="mt-4">
              <div className="text-sm font-medium mb-2">Line items of bill {items.billId}</div>
              <DataTable rows={items.results} filename={`bill-${items.billId}.csv`} />
            </div>
          )}
        </div>

        {isBilling && (
          <div>
            <div className={panelCls}>
              <div className={panelHeadCls}><h2 className="text-lg font-display m-0 flex items-center gap-2"><CreditCard size={18} className="text-accent" /> Record payment</h2></div>
              <form onSubmit={submitPayment}>
                <div className="grid gap-3 grid-cols-1 sm:grid-cols-3">
                  <Field label="Bill ID"><input className={inputCls} value={payment.bill_id} onChange={(e) => setPayment({ ...payment, bill_id: e.target.value })} required /></Field>
                  <Field label="Amount (₹)"><input className={inputCls} type="number" min={1} step="0.01" value={payment.amount_paid} onChange={(e) => setPayment({ ...payment, amount_paid: e.target.value })} required /></Field>
                  <Field label="Mode">
                    <select className={inputCls} value={payment.payment_mode} onChange={(e) => setPayment({ ...payment, payment_mode: e.target.value })}>
                      {MODES.map((m) => <option key={m} value={m}>{m.replace("_", " ")}</option>)}
                    </select>
                  </Field>
                </div>
                <button type="submit" className={btnPrimary}>Record payment</button>
                <p className="text-xs text-ink-muted mb-0">Paying more than the balance is refused (ORA-20040).</p>
              </form>
            </div>
            <div className={panelCls}>
              <div className={panelHeadCls}><h2 className="text-lg font-display m-0 flex items-center gap-2"><Receipt size={18} className="text-accent" /> Generate bill for a visit</h2></div>
              <form onSubmit={generate}>
                <div className="grid gap-3 grid-cols-2">
                  <Field label="Appointment ID"><input className={inputCls} value={gen.appointment_id} onChange={(e) => setGen({ ...gen, appointment_id: e.target.value })} required /></Field>
                  <Field label="Patient ID"><input className={inputCls} value={gen.patient_id} onChange={(e) => setGen({ ...gen, patient_id: e.target.value })} required /></Field>
                </div>
                <button type="submit" className={btnGhost}>Generate bill</button>
                <p className="text-xs text-ink-muted mb-0">Mark today's appointment COMPLETED on the Appointments page first. A second bill for the same visit is refused (ORA-20041).</p>
              </form>
            </div>
          </div>
        )}
      </div>

      {isBilling && (
        <div className={panelCls}>
          <div className={panelHeadCls}>
            <h2 className="text-lg font-display m-0 flex items-center gap-2"><AlertTriangle size={18} className="text-warn" /> Outstanding bills (vw_outstanding_bills)</h2>
            <div className="flex gap-2 items-center">
              <select className={`${inputCls} w-40`} value={bucket} onChange={(e) => setBucket(e.target.value)}>
                <option value="">All ages</option><option value="0-30">0-30 days</option><option value="31-90">31-90 days</option><option value="90+">90+ days</option>
              </select>
              <button className={btnGhost} onClick={outstanding.reload}><RefreshCw size={15} /></button>
            </div>
          </div>
          {outstanding.data && <>
            <DataTable rows={outstanding.data.results} filename="outstanding-bills.csv" maxHeight={420} emptyMessage="Nothing outstanding." />
            <SqlPanel sql={outstanding.data.sql_executed} meta={outstanding.data} />
          </>}
        </div>
      )}
    </div>
  );
}
